"""Writes results/M1_cbba_report.md: the measured numbers behind the M1 checks (random instances, brute force, legacy comparison)."""
import json, os, random, sys, time
from pathlib import Path
sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(HERE)); sys.path.insert(0, str(HERE / "tests"))
import test_cbba as t
from shield import alloc, paths

def main():
    n = int(os.environ.get("EDGESAR_TEST_N", "10000"))
    out = {}
    # random instances: with and without bid warping, full graph and line graph
    for name, kw in (("full graph, warping on", {}), ("full graph, warping OFF", {"warp": False}), ("line graph, warping on", {"graph": "line"}),
                     ("bundle length 1", {"bundle_len": 1})):
        rng = random.Random(20261113)
        st = dict(instances=0, nonconv=0, worst_rounds=0, placed=0, warps=0, releases=0)
        t0 = time.perf_counter()
        for _ in range(n):
            pr = t.random_instance(rng)
            al = alloc.BoundedCBBA(**kw)
            p = al.plan(pr)
            t.conflict_free(p)
            st["instances"] += 1
            st["nonconv"] += p.info["nonconverged"]
            st["worst_rounds"] = max(st["worst_rounds"], p.info["max_rounds_one_auction"])
            st["placed"] += p.info["placed"]; st["warps"] += p.info["warps"]; st["releases"] += p.info["releases"]
        st["ms_per_instance"] = round((time.perf_counter() - t0) * 1000 / n, 3)
        out[name] = st
    t.test_ratio_to_brute_force_small_instances()
    out["brute_force"] = t.test_ratio_to_brute_force_small_instances.report
    t.test_L1_first_assignments_equal_legacy_on_pilot_gold_tables()
    out["legacy_vs_L1_first_assignments"] = t.test_L1_first_assignments_equal_legacy_on_pilot_gold_tables.report
    res = HERE / "results"; res.mkdir(exist_ok=True)
    (res / "M1_cbba_report.json").write_text(json.dumps(out, indent=1), encoding="utf-8")
    L = ["# M1: bounded CBBA, measured checks", "",
         "Generated by `tools/m1_report.py`. Random instances: up to 4 UAVs and 12 tasks, random positions, speeds, cameras, busy times, bans.", "",
         "| Setting | Instances | Not converged | Worst rounds (one auction) | Bids placed | Bids lowered by warping | Bundle releases | ms per instance |", "|---|---|---|---|---|---|---|---|"]
    for k in ("full graph, warping on", "full graph, warping OFF", "line graph, warping on", "bundle length 1"):
        s = out[k]
        L.append("| %s | %d | %d | %d | %d | %d (%.2f%%) | %d | %.2f |" % (k, s["instances"], s["nonconv"], s["worst_rounds"], s["placed"], s["warps"],
                                                                         100.0 * s["warps"] / max(1, s["placed"]), s["releases"], s["ms_per_instance"]))
    L += ["", "## Ratio of the total score to the best possible (brute force, 2-3 UAVs, 2-6 tasks, 150 instances)", "",
          "| Allocator | Mean ratio | Worst ratio |", "|---|---|---|"]
    for k, v in out["brute_force"].items():
        L.append("| %s | %.3f | %.3f |" % (k, v["mean"], v["min"]))
    L += ["", "The 50 % guarantee of the CBBA paper is not relied on. These are measured ratios on small instances only.", "",
          "## Bounded CBBA with bundle length 1 against `legacy_greedy_s1` on the 1,400 pilot gold tables", "",
          "First assignments identical in %d of %d tables; different: %d." % (out["legacy_vs_L1_first_assignments"]["same_first_assignment"],
                                                                         out["legacy_vs_L1_first_assignments"]["tables"], out["legacy_vs_L1_first_assignments"]["different"])]
    (res / "M1_cbba_report.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))

if __name__ == "__main__":
    main()
